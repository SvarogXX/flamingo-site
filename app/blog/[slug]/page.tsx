interface TocItem {
  id: string;
  title: string;
  level: 2 | 3;
}

function slugifyHeading(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .trim()
    .replace(/\s+/g, "-");
}

function formatInlineMarkdown(value: string): string {
  return value.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
}

function renderArticleContent(markdown: string): { html: string; toc: TocItem[] } {
  const lines = markdown.trim().split("\n");
  const htmlParts: string[] = [];
  const toc: TocItem[] = [];

  let inList = false;
  let paragraphBuffer: string[] = [];
  let shouldUseLeadParagraph = false;

  const closeList = () => {
    if (inList) {
      htmlParts.push("</ul>");
      inList = false;
    }
  };

  const flushParagraph = () => {
    if (paragraphBuffer.length === 0) {
      return;
    }

    const paragraph = paragraphBuffer.join(" ");
    if (shouldUseLeadParagraph) {
      htmlParts.push(`<p class="lead-paragraph">${formatInlineMarkdown(paragraph)}</p>`);
      shouldUseLeadParagraph = false;
    } else {
      htmlParts.push(`<p>${formatInlineMarkdown(paragraph)}</p>`);
    }
    paragraphBuffer = [];
  };

  for (const rawLine of lines) {
    const line = rawLine.trim();

    if (!line) {
      flushParagraph();
      closeList();
      continue;
    }

    if (line.startsWith("## ")) {
      flushParagraph();
      closeList();
      const title = line.replace(/^##\s+/, "").trim();
      const id = slugifyHeading(title);
      toc.push({ id, title, level: 2 });
      htmlParts.push(`<h2 id="${id}" class="scroll-mt-32">${formatInlineMarkdown(title)}</h2>`);
      shouldUseLeadParagraph = true;
      continue;
    }

    if (line.startsWith("### ")) {
      flushParagraph();
      closeList();
      const title = line.replace(/^###\s+/, "").trim();
      const id = slugifyHeading(title);
      toc.push({ id, title, level: 3 });
      htmlParts.push(`<h3 id="${id}" class="scroll-mt-32">${formatInlineMarkdown(title)}</h3>`);
      shouldUseLeadParagraph = false;
      continue;
    }

    if (line.startsWith("- ")) {
      flushParagraph();
      shouldUseLeadParagraph = false;
      if (!inList) {
        htmlParts.push('<ul class="not-prose my-8 space-y-3">');
        inList = true;
      }

      const item = line.replace(/^-\s+/, "").trim();
      htmlParts.push(`<li class="rounded-xl border border-white/10 bg-white/[0.03] px-5 py-4 text-[1.05rem] font-light text-slate-500 leading-8">${formatInlineMarkdown(item)}</li>`);
      continue;
    }

    // Markdown image: ![alt](src)
    const imgMatch = line.match(/^!\[([^\]]*)\]\(([^)]+)\)\s*$/);
    if (imgMatch) {
      flushParagraph();
      closeList();
      const [, alt, src] = imgMatch;
      htmlParts.push(`<figure class="my-10"><img src="${src}" alt="${alt.replace(/"/g, "&quot;")}" class="w-full rounded-2xl border border-white/10 shadow-xl object-cover" /></figure>`);
      shouldUseLeadParagraph = false;
      continue;
    }

    closeList();
    paragraphBuffer.push(line);
  }

  flushParagraph();
  closeList();

  return {
    html: htmlParts.join("\n"),
    toc,
  };
}

